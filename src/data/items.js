/** 把元组转换成商品对象 */
function toItem(row, index) {
  const [title, category, price, originalPrice, condition, spot, daysAgo, views, tags, desc] = row
  const seller = SELLERS[index % SELLERS.length]
  return {
    id: `ny-${String(index + 1).padStart(3, '0')}`,
    title,
    category,
    price,
    originalPrice,
    condition,
    spot,
    publishedAt: NOW - daysAgo * DAY - (index % 7) * 3600 * 1000,
    views,
    tags,
    description: desc,
    seller,
    negotiable: price >= 100, // 演示用：100 元以上默认可议价
    likes: 3 + ((index * 7) % 26),
  }
}

